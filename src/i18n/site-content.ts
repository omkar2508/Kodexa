export type SiteCopyKey = keyof (typeof siteContent)["en"];
export type SiteText = (key: SiteCopyKey) => string;

export function siteText(t: SiteText, key: string): string {
  return t(key as SiteCopyKey);
}

export function localizeService<
  T extends {
    slug: string;
    title: string;
    desc: string;
    items: string[];
    useCases: string[];
  },
>(service: T, t: SiteText): T {
  const key = (suffix: string) => `service.${service.slug}.${suffix}` as SiteCopyKey;
  return {
    ...service,
    title: t(key("title")),
    desc: t(key("desc")),
    items: service.items.map((_, index) => t(key(`item.${index}`))),
    useCases: service.useCases.map((_, index) => t(key(`use.${index}`))),
  };
}

export function localizeIndustry<
  T extends {
    name: string;
    text: string;
    solutions: string[];
  },
>(industry: T, index: number, t: SiteText): T {
  const key = (suffix: string) => `industry.${index}.${suffix}` as SiteCopyKey;
  return {
    ...industry,
    name: t(key("name")),
    text: t(key("text")),
    solutions: industry.solutions.map((_, itemIndex) => t(key(`solution.${itemIndex}`))),
  };
}

export function localizeProcess<T extends [string, string]>(
  step: T,
  index: number,
  t: SiteText,
): T {
  return [
    t(`process.${index}.title` as SiteCopyKey),
    t(`process.${index}.text` as SiteCopyKey),
  ] as T;
}

export function localizeFaq<T extends [string, string]>(faq: T, index: number, t: SiteText): T {
  return [t(`faq.${index}.q` as SiteCopyKey), t(`faq.${index}.a` as SiteCopyKey)] as T;
}

export function localizeRole(role: string, t: SiteText): string {
  const roleKey: Record<string, SiteCopyKey> = {
    "Built by our team": "portfolio.role.built",
    "Team contribution": "portfolio.role.contribution",
    "Industry reference": "portfolio.role.reference",
    "Team role pending": "portfolio.role.pending",
  };
  return roleKey[role] ? t(roleKey[role]) : role;
}

export function localizeProject<
  T extends {
    slug: string;
    summary: string;
    role: string;
    draftNote?: string;
    details?: {
      context?: string;
      problem?: string;
      requirements?: string[];
      solution?: string;
      features?: string[];
      design?: string;
      implementation?: string;
      contribution?: string;
      results?: string;
    };
  },
>(project: T, t: SiteText): T {
  const translated = (suffix: string, fallback: string) => {
    const value = t(`project.${project.slug}.${suffix}` as SiteCopyKey);
    return value.startsWith("project.") ? fallback : value;
  };
  const details = project.details
    ? {
        ...project.details,
        context: project.details.context
          ? translated("context", project.details.context)
          : undefined,
        problem: project.details.problem
          ? translated("problem", project.details.problem)
          : undefined,
        requirements: project.details.requirements?.map((item, index) =>
          translated(`requirement.${index}`, item),
        ),
        solution: project.details.solution
          ? translated("solution", project.details.solution)
          : undefined,
        features: project.details.features?.map((item, index) =>
          translated(`feature.${index}`, item),
        ),
        design: project.details.design ? translated("design", project.details.design) : undefined,
        implementation: project.details.implementation
          ? translated("implementation", project.details.implementation)
          : undefined,
        contribution: project.details.contribution
          ? translated("contribution", project.details.contribution)
          : undefined,
        results: project.details.results
          ? translated("results", project.details.results)
          : undefined,
      }
    : undefined;
  return {
    ...project,
    summary: translated("summary", project.summary),
    draftNote: project.draftNote ? translated("note", project.draftNote) : undefined,
    details,
  };
}

